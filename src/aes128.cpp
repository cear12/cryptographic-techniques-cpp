Aes128::Aes128(const Key& key) { expandKey(key); }

void Aes128::expandKey(const Key& key) {
    // Words are 4-byte chunks; AES-128 has Nk=4, Nr=10 -> 44 words total.
    std::array<std::array<std::uint8_t, 4>, 44> w{};
    for (int i = 0; i < 4; ++i) {
        for (int b = 0; b < 4; ++b) w[static_cast<std::size_t>(i)][b] = key[static_cast<std::size_t>(i * 4 + b)];
    }

    for (int i = 4; i < 44; ++i) {
        std::array<std::uint8_t, 4> temp = w[static_cast<std::size_t>(i - 1)];
        if (i % 4 == 0) {
            // RotWord + SubWord + Rcon.
            std::array<std::uint8_t, 4> rotated = {temp[1], temp[2], temp[3], temp[0]};
            for (auto& byte : rotated) byte = sbox()[byte];
            rotated[0] ^= rcon()[static_cast<std::size_t>(i / 4)];
            temp = rotated;
        }
        for (int b = 0; b < 4; ++b) {
            w[static_cast<std::size_t>(i)][static_cast<std::size_t>(b)] =
                w[static_cast<std::size_t>(i - 4)][static_cast<std::size_t>(b)] ^ temp[static_cast<std::size_t>(b)];
        }
    }

    for (int i = 0; i < 44; ++i) {
        std::memcpy(roundKeys_.data() + i * 4, w[static_cast<std::size_t>(i)].data(), 4);
    }
}

Aes128::Block Aes128::encryptBlock(const Block& plaintext) const {
    std::array<std::uint8_t, 16> state;
    std::memcpy(state.data(), plaintext.data(), 16);

    addRoundKey(state.data(), roundKeys_.data());
    for (int round = 1; round < kRounds; ++round) {
        subBytes(state.data());
        shiftRows(state.data());
        mixColumns(state.data());
        addRoundKey(state.data(), roundKeys_.data() + round * 16);
    }
    subBytes(state.data());
    shiftRows(state.data());
    addRoundKey(state.data(), roundKeys_.data() + kRounds * 16);

    Block out;
    std::memcpy(out.data(), state.data(), 16);
    return out;
}

Aes128::Block Aes128::decryptBlock(const Block& ciphertext) const {
    std::array<std::uint8_t, 16> state;
    std::memcpy(state.data(), ciphertext.data(), 16);

    addRoundKey(state.data(), roundKeys_.data() + kRounds * 16);
    for (int round = kRounds - 1; round > 0; --round) {
        invShiftRows(state.data());
        invSubBytes(state.data());
        addRoundKey(state.data(), roundKeys_.data() + round * 16);
        invMixColumns(state.data());
    }
    invShiftRows(state.data());
    invSubBytes(state.data());
    addRoundKey(state.data(), roundKeys_.data());

    Block out;
    std::memcpy(out.data(), state.data(), 16);
    return out;
}

